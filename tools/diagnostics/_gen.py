L('def _parse_period_year(period: Optional[str]) -> Optional[int]:')
L('    """Extract year integer from period string."""')
L('    if not period:')
L('        return None')
L('    period = str(period).strip()')
L('    for part in period.split():')
L('        if part.isdigit() and len(part) == 4:')
L('            return int(part)')
L('    if "-" in period:')
L('        for part in period.split("-"):')
L('            part = part.strip()')
L('            if part.isdigit():')
L('                year = int(part)')
L('                return 2000 + year if year < 100 else year')
L('    return None')
L('')
L('')
L('def _deduplicate_annual(records: List[Dict[str, Any]]) -> List[Dict[str, Any]]:')
L('    """Keep only the latest entry per year."""')
L('    year_map: Dict[int, Dict[str, Any]] = {}')
L('    for rec in records:')
L('        year = _parse_period_year(rec.get("period"))')
L('        if year is None:')
L('            continue')
L('        if year not in year_map:')
L('            year_map[year] = rec')
L('    result = sorted(')
L('        year_map.values(),')
L('        key=lambda r: _parse_period_year(r.get("period")) or 0,')
L('        reverse=True,')
