L('        avg_change = -avg_change')
L('    if avg_change <= 0:')
L('        return CONFIDENCE_BASE')
L('    confidence = CONFIDENCE_BASE + avg_change * CONFIDENCE_DISTANCE_FACTOR')
L('    confidence = max(CONFIDENCE_MIN, min(CONFIDENCE_MAX, confidence))')
L('    return round(confidence, 2)')
